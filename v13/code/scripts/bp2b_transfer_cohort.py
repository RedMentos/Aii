#!/usr/bin/env python3
"""WP-BP2b: frozen software-only source-disjoint paraphrase transfer cohort.

No model is loaded. The model-facing prompts JSONL contains ONLY case_id/prompt,
never expected answers, source facts, answer keys, or a teacher completion.
A separate scoring-only JSON file is explicitly not an inference input.
Native training and Q4 comparison require a later serial owner/provenance check.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

import numpy as np

from scripts.bj1_body_jepa import POOL
from scripts.bp2a_leak import TRAIN_NM
from v13.common import atomic_write
from v13.locality_anchors import TRAIN_SUBJECTS, generate_anchors
from v13.lora_trainer import LoraTrainer

REVISION = 'bp2b-transfer-source-v1'
SEEDS = (41, 42, 43)
FACTS = 16
EVAL_SUBJECTS = ('roommate', 'partner', 'niece', 'landlord', 'mentor', 'coach')
# Two independently written paraphrases per source fact, in POOL order.
# These are NOT generated by the grammar used for the training anchors.
HOLDOUT = (
    ('What name does my roommate use for their cat?', 'Can you tell me what my landlord calls their cat?'),
    ('Which employer pays my partner?', 'Who does my coach work for?'),
    ('Which shade is my niece most fond of?', 'What colour does my mentor like best?'),
    ("Who is my roommate's brother?", "Can you name my landlord's brother?"),
    ('What instrument has my partner learned to play?', 'Which musical instrument does my coach practise?'),
    ('What title did my niece give her project?', "Can you tell me my mentor's project's name?"),
    ('On which date was my landlord born?', 'What day does my roommate celebrate their birthday?'),
    ('What name did my partner give their boat?', 'How does my mentor refer to their boat?'),
    ('Where did my niece relocate last year?', 'To what city did my coach move last year?'),
    ('Which meal does my landlord enjoy the most?', 'What food does my roommate prefer?'),
    ("How is my partner's parrot named?", 'What does my mentor call their parrot?'),
    ('Which football team does my niece root for?', 'What club is my coach a fan of?'),
    ('What book would my landlord pick as a favourite?', 'Which novel does my roommate like best?'),
    ("Who is my partner's grandfather?", "Can you name my mentor's grandfather?"),
    ('What foreign language is my niece studying?', 'Which language has my coach started learning?'),
    ('Which board game does my landlord prefer?', 'What tabletop game does my roommate enjoy most?'),
    ("Which road is my partner's home on?", 'What street does my mentor live on?'),
    ('What does my niece call her goldfish?', 'Which name did my coach give their goldfish?'),
    ('Which blood group does my landlord have?', "Do you know my roommate's blood type?"),
    ('What peak did my partner climb last summer?', 'Which summit did my mentor reach last summer?'),
    ("Which teacher was my niece's favourite at school?", "Who was my coach's best teacher in school?"),
    ('What kind of flower does my landlord like best?', 'Which bloom does my roommate prefer?'),
    ('What name does my partner use for their tortoise?', 'How did my mentor name their tortoise?'),
    ('Which music group did my niece attend a show by last month?',
     'What band did my coach watch perform last month?'),
)


def _bytes(obj):
    return json.dumps(obj, sort_keys=True, separators=(',', ':'), ensure_ascii=False,
                      allow_nan=False).encode('utf-8')


def _hash(obj):
    return hashlib.sha256(_bytes(obj)).hexdigest()


def validate():
    """Fail closed on source/heldout contamination before any data are emitted."""
    if len(POOL) != 24 or len(TRAIN_NM) != 24 or len(HOLDOUT) != 24:
        raise ValueError('Expected exact frozen 24-fact source and near-miss cohort')
    if set(EVAL_SUBJECTS) & set(TRAIN_SUBJECTS):
        raise ValueError('Training/evaluation subject collision')
    all_train = [{'prompt': row[0]} for row in POOL]
    automatic = set(generate_anchors(all_train, 2))
    legacy = set(LoraTrainer.locality_prompts(all_train, 2))
    manual = {p for pair in TRAIN_NM for p in pair}
    old_eval = {row[4] for row in POOL}
    old_para = {p for row in POOL for p in row[3]}
    old_source = {row[0] for row in POOL}
    seen = set()
    for i, pair in enumerate(HOLDOUT):
        if type(pair) is not tuple or len(pair) != 2:
            raise ValueError('Expected two fixed heldout paraphrases per source')
        keys = POOL[i][2]
        for prompt in pair:
            if (type(prompt) is not str or len(prompt) > 256 or prompt.count('?') != 1
                    or not prompt.endswith('?') or prompt in seen
                    or prompt in automatic | legacy | manual | old_eval | old_para | old_source):
                raise ValueError('Heldout prompt malformed, duplicated or trained')
            if not any(re.search(r'\bmy ' + re.escape(s) + r"\b", prompt, re.I)
                       for s in EVAL_SUBJECTS):
                raise ValueError('Heldout subject missing')
            if any(re.search(r'\bmy ' + re.escape(s) + r"\b", prompt, re.I)
                   for s in TRAIN_SUBJECTS):
                raise ValueError('Heldout subject overlaps training substitutions')
            if any(str(k).casefold() in prompt.casefold() for k in keys):
                raise ValueError('Expected answer leaked into heldout prompt')
            seen.add(prompt)
    return {'source_sha256': _hash(POOL), 'heldout_sha256': _hash(HOLDOUT),
            'manual_anchor_sha256': _hash(TRAIN_NM), 'all_heldout_count': len(seen)}


def cohort(seed):
    """Return manifest, inference-only prompts, and scoring-only keys (separate)."""
    if type(seed) is not int or seed not in SEEDS:
        raise ValueError('Seed is not part of the frozen cohort')
    proof = validate()
    indices = sorted(int(i) for i in np.random.default_rng(seed).choice(len(POOL), FACTS, replace=False))
    train = [{'memory_id': 'bp2b_%02d' % i, 'prompt': POOL[i][0],
              'target': POOL[i][1], 'answer_keys': POOL[i][2]} for i in indices]
    model_facing = [{'case_id': 'bp2b_%02d_%d' % (i, j), 'prompt': HOLDOUT[i][j]}
                    for i in indices for j in range(2)]
    scoring_only = [{'case_id': 'bp2b_%02d_%d' % (i, j), 'answer_keys': POOL[i][2]}
                    for i in indices for j in range(2)]
    if set().union(*(set(r) for r in model_facing)) != {'case_id', 'prompt'}:
        raise ValueError('Model-facing schema contains extra fields')
    manifest = {'schema': REVISION, 'seed': seed, 'selected_indices': indices,
                'facts': FACTS, 'heldout_rows': len(model_facing), **proof,
                'train_sha256': _hash(train), 'model_facing_sha256': _hash(model_facing),
                'scoring_only_sha256': _hash(scoring_only),
                'arms': ['legacy', 'bp2b', 'bp2b_minor', 'manual_ref'],
                'status': 'SOURCE_ONLY_NATIVE_NOT_RUN',
                'age_authority': 0, 'jepa_weight': 0}
    return manifest, model_facing, scoring_only


def _write_immutable(path, payload):
    path = Path(path)
    if path.exists():
        if path.read_bytes() != payload:
            raise ValueError('Refusing to overwrite a different frozen cohort file')
        return
    atomic_write(path, payload)


def prepare(out, seed):
    manifest, model_facing, scoring_only = cohort(seed)
    dest = Path(out) / ('seed-%d' % seed)
    _write_immutable(dest / 'model_facing.jsonl',
                     b''.join(_bytes(row) + b'\n' for row in model_facing))
    _write_immutable(dest / 'scoring_only.json',
                     json.dumps(scoring_only, indent=2, ensure_ascii=False).encode('utf-8') + b'\n')
    _write_immutable(dest / 'manifest.json',
                     json.dumps(manifest, indent=2, ensure_ascii=False).encode('utf-8') + b'\n')
    return manifest


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--seed', type=int, required=True, choices=SEEDS)
    ap.add_argument('--prepare-only', action='store_true', required=True,
                    help='source-only; never loads a model or starts training')
    a = ap.parse_args(argv)
    print(json.dumps(prepare(a.out, a.seed), sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
